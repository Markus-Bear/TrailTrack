-- The schema as it was at release v0.1, when Hibernate created the tables.
-- Constraint names are the ones Hibernate generated, so databases created
-- before Flyway can be baselined at this version and match exactly.

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE trails (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    county varchar(255),
    description text,
    difficulty varchar(255),
    geom geometry(MultiLineString, 4326),
    grade varchar(255),
    length_km double precision,
    name text NOT NULL,
    source_trail_id integer NOT NULL,
    time_to_complete varchar(255),
    trail_type varchar(255),
    website text,
    trailhead geometry(Point, 4326),
    waymarking text,
    CONSTRAINT trails_pkey PRIMARY KEY (id),
    CONSTRAINT ukyc5aj59ygesx8d91ycj19e7u UNIQUE (source_trail_id)
);

-- Distance searches measure on the geography type, so the index is on that.
CREATE INDEX idx_trails_geom_geography ON trails USING gist ((geom::geography));

CREATE TABLE users (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at timestamp(6) with time zone NOT NULL,
    display_name varchar(50) NOT NULL,
    email varchar(254) NOT NULL,
    password_hash varchar(255) NOT NULL,
    role varchar(20) NOT NULL,
    CONSTRAINT users_pkey PRIMARY KEY (id),
    CONSTRAINT uk6dotkott2kjsp8vw4d0m25fb7 UNIQUE (email),
    CONSTRAINT users_role_check CHECK (role IN ('HIKER', 'ADMIN'))
);

CREATE TABLE condition_reports (
    id bigint GENERATED BY DEFAULT AS IDENTITY,
    client_ref uuid NOT NULL,
    condition_type varchar(20) NOT NULL,
    note varchar(500),
    reported_at timestamp(6) with time zone NOT NULL,
    severity varchar(10),
    status varchar(20) NOT NULL,
    trail_id bigint NOT NULL,
    user_id bigint NOT NULL,
    CONSTRAINT condition_reports_pkey PRIMARY KEY (id),
    CONSTRAINT uk7bl0vappbro13lf9ttdvs0mug UNIQUE (client_ref),
    CONSTRAINT fkgbg8oxrijxrvl2ayijxxyd8b3 FOREIGN KEY (trail_id) REFERENCES trails (id),
    CONSTRAINT fk7hh6pkc3p3al5d7yrlgigimxx FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT condition_reports_condition_type_check CHECK (condition_type IN
        ('CLEAR', 'MUD', 'FLOODING', 'FALLEN_TREE', 'STORM_DAMAGE', 'CLOSURE',
         'FORESTRY_WORK', 'LIVESTOCK', 'OTHER')),
    CONSTRAINT condition_reports_severity_check CHECK (severity IN ('LOW', 'MODERATE', 'HIGH')),
    CONSTRAINT condition_reports_status_check CHECK (status IN
        ('OPEN', 'CORROBORATED', 'ACKNOWLEDGED', 'RESOLVED', 'EXPIRED', 'REMOVED'))
);

CREATE INDEX idx_condition_reports_trail_time ON condition_reports (trail_id, reported_at);
